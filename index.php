                /* Staggered card reveal for fleet, service, FAQ, benefit, contact, quick items, review cards, footer */
                const cardObserver = new IntersectionObserver((entries) => {
                    entries.forEach(entry => {
                        if (entry.isIntersecting) {
                            entry.target.classList.add('revealed');
                            entry.target.style.opacity = '';
                            cardObserver.unobserve(entry.target);
                        }
                    });
                }, { threshold: 0.08, rootMargin: '0px 0px -30px 0px' });

                document.querySelectorAll(
                    '.fleet-card, .service-card, .faq, .benefit, .contact-card, .quick-item, .review-card, footer .footer-grid > div'
                ).forEach(el => {
                    /* Set initial hidden state via JS so non-JS users see content */
                    el.style.opacity = '0';
                    cardObserver.observe(el);
                });

                /* 8. PARALLAX SCROLL EFFECT ON HERO */
                const heroSlider = document.querySelector('.hero-slider');
                let ticking = false;

                function handleParallax() {
                    const scrollY = window.scrollY;
                    const heroH = heroSlider ? heroSlider.offsetHeight : 700;
                    if (scrollY <= heroH && heroSlider) {
                        const offset = scrollY * 0.25;
                        heroSlider.style.transform = `translateY(${offset}px)`;
                        heroSlider.style.opacity = `${1 - scrollY / (heroH * 1.5)}`;
                    }
                    ticking = false;
                }

                window.addEventListener('scroll', () => {
                    if (!ticking) {
                        requestAnimationFrame(handleParallax);
                        ticking = true;
                    }
                }, { passive: true });

                /* 9. FLOATING PARTICLES GENERATOR */
                function createParticles(containerId, count) {
                    const container = document.getElementById(containerId);
                    if (!container) return;
                    for (let i = 0; i < count; i++) {
                        const p = document.createElement('span');
                        p.classList.add('particle');
                        const size = Math.random() * 5 + 2;
                        p.style.width = size + 'px';
                        p.style.height = size + 'px';
                        p.style.left = Math.random() * 100 + '%';
                        p.style.top = Math.random() * 100 + '%';
                        p.style.animationDuration = (Math.random() * 8 + 6) + 's';
                        p.style.animationDelay = (Math.random() * 5) + 's';
                        container.appendChild(p);
                    }
                }

                createParticles('serviceParticles', 18);

                /* 10. SMOOTH NUMBER COUNTER ANIMATION */
                function animateCounter(el, end, suffix) {
                    const duration = 1800;
                    const startTime = performance.now();
                    const startVal = 0;

                    function tick(now) {
                        const elapsed = now - startTime;
                        const progress = Math.min(elapsed / duration, 1);
                        // ease-out cubic
                        const ease = 1 - Math.pow(1 - progress, 3);
                        const current = Math.round(startVal + (end - startVal) * ease);
                        el.textContent = current + (suffix || '');
                        if (progress < 1) {
                            requestAnimationFrame(tick);
                        }
                    }

                    requestAnimationFrame(tick);
                }

                /* Activate counter when quick-wrap enters viewport */
                const quickWrap = document.querySelector('.quick-wrap');
                if (quickWrap) {
                    let counterActivated = false;
                    const counterObserver = new IntersectionObserver((entries) => {
                        entries.forEach(entry => {
                            if (entry.isIntersecting && !counterActivated) {
                                counterActivated = true;
                                document.querySelectorAll('.quick-text strong[data-count]').forEach(el => {
                                    const end = parseInt(el.getAttribute('data-count'), 10);
                                    const suffix = el.getAttribute('data-suffix') || '';
                                    if (!isNaN(end)) {
                                        animateCounter(el, end, suffix);
                                    }
                                });
                                counterObserver.unobserve(entry.target);
                            }
                        });
                    }, { threshold: 0.3 });
                    counterObserver.observe(quickWrap);
                }

                /* 11. ACTIVE NAV LINK HIGHLIGHT ON SCROLL */
                const navLinks = document.querySelectorAll('.desktop-nav-links a');
                const sections = document.querySelectorAll('section[id]');
                const sectionObserver = new IntersectionObserver((entries) => {
                    entries.forEach(entry => {
                        if (entry.isIntersecting) {
                            const id = entry.target.getAttribute('id');
                            navLinks.forEach(link => {
                                link.style.color = '';
                                if (link.getAttribute('href') === '#' + id) {
                                    link.style.color = 'var(--gold)';
                                }
                            });
                        }
                    });
                }, { threshold: 0.25, rootMargin: '-80px 0px -50% 0px' });
                sections.forEach(sec => sectionObserver.observe(sec));

            } /* End reduced motion check */

            /* 12. INSTANT BOOKING MODAL LOGIC */
            const bookingModal = document.getElementById('bookingModal');
            const modalCloseBtn = document.getElementById('modalCloseBtn');
            const bookingForm = document.getElementById('modalBookingForm');
            const vehicleSelect = document.getElementById('modalVehicleSelect');

            function openModal(vehicleName) {
                if (!bookingModal) return;
                if (vehicleName && vehicleSelect) {
                    for (let i = 0; i < vehicleSelect.options.length; i++) {
                        if (vehicleSelect.options[i].value.toLowerCase().includes(vehicleName.toLowerCase())) {
                            vehicleSelect.selectedIndex = i;
                            break;
                        }
                    }
                }
                bookingModal.classList.add('active');
                document.body.style.overflow = 'hidden';
            }

            function closeModal() {
                if (!bookingModal) return;
                bookingModal.classList.remove('active');
                document.body.style.overflow = '';
            }

            document.querySelectorAll('.btn-open-modal').forEach(btn => {
                btn.addEventListener('click', (e) => {
                    e.preventDefault();
                    const v = btn.getAttribute('data-vehicle') || '';
                    openModal(v);
                });
            });

            if (modalCloseBtn) modalCloseBtn.addEventListener('click', closeModal);

            if (bookingModal) {
                bookingModal.addEventListener('click', (e) => {
                    if (e.target === bookingModal) closeModal();
                });
            }

            document.addEventListener('keydown', (e) => {
                if (e.key === 'Escape' && bookingModal && bookingModal.classList.contains('active')) {
                    closeModal();
                }
            });

            if (bookingForm) {
                bookingForm.addEventListener('submit', (e) => {
                    e.preventDefault();
                    const vehicle = vehicleSelect ? vehicleSelect.value : 'Vehicle Rental';
                    const tripType = document.getElementById('modalTripType') ? document.getElementById('modalTripType').value : '';
                    const travelDate = document.getElementById('modalDate') ? document.getElementById('modalDate').value : '';
                    const name = document.getElementById('modalName') ? document.getElementById('modalName').value.trim() : '';
                    const phone = document.getElementById('modalPhone') ? document.getElementById('modalPhone').value.trim() : '';
                    const pickup = document.getElementById('modalPickup') ? document.getElementById('modalPickup').value.trim() : '';

                    let msg = `Hello VSM Tours & Travels, I want to book a vehicle:\n\n`;
                    msg += `🚗 Vehicle: ${vehicle}\n`;
                    if (tripType) msg += `📍 Trip Type: ${tripType}\n`;
                    if (travelDate) msg += `📅 Date: ${travelDate}\n`;
                    if (pickup) msg += `📌 Pickup: ${pickup}\n`;
                    if (name) msg += `👤 Name: ${name}\n`;
                    if (phone) msg += `📞 Mobile: ${phone}\n`;

                    const waUrl = `https://wa.me/919866430088?text=${encodeURIComponent(msg)}`;
                    window.open(waUrl, '_blank');
                    closeModal();
                });
            }

            /* 13. FLEET FILTERING LOGIC */
            const filterButtons = document.querySelectorAll('.fleet-filter-btn');
            const fleetCards = document.querySelectorAll('.fleet-card');

            filterButtons.forEach(btn => {
                btn.addEventListener('click', () => {
                    filterButtons.forEach(b => {
                        b.classList.remove('active');
                        b.setAttribute('aria-selected', 'false');
                    });
                    btn.classList.add('active');
                    btn.setAttribute('aria-selected', 'true');

                    const filter = btn.getAttribute('data-filter');
                    fleetCards.forEach(card => {
                        const categories = (card.getAttribute('data-category') || '').split(' ');
                        if (filter === 'all' || categories.includes(filter)) {
                            card.classList.remove('filtered-out');
                        } else {
                            card.classList.add('filtered-out');
                        }
                    });
                });
            });

            /* 14. FLOATING BACK TO TOP BUTTON */
            const backToTopBtn = document.getElementById('backToTop');
            window.addEventListener('scroll', () => {
                if (backToTopBtn) {
                    backToTopBtn.classList.toggle('visible', window.scrollY > 380);
                }
            }, { passive: true });

            if (backToTopBtn) {
                backToTopBtn.addEventListener('click', () => {
                    window.scrollTo({ top: 0, behavior: 'smooth' });
                });
            }
        });
    </script>

